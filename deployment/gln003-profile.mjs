// tests/gln003-profile.worker.ts
var SOURCE_ID = "gln003-cf-status";
var SOURCE_URL = "https://www.cloudflarestatus.com/history.atom";
var PLAN_ID = "gln003-profile-v1";
var MAX_RUNS = 9;
var gln003_profile_worker_default = {
  fetch: src_default.fetch,
  async scheduled(event, env, _ctx) {
    const plan = await env.DB.prepare(`
      UPDATE gln003_profile_plan SET run = run + 1
      WHERE id=? AND run < ?
      RETURNING run
    `).bind(PLAN_ID, MAX_RUNS).first();
    if (!plan) return;
    const source = await env.DB.prepare("SELECT url FROM poc_sources WHERE id=?").bind(SOURCE_ID).first();
    if (source?.url !== SOURCE_URL) throw new Error("unexpected_canary_source");
    const mode = ["fetch", "parse", "full"][(plan.run - 1) % 3];
    const start = Date.now();
    let articles = 0, inserted = 0, success = false;
    let errorCode = "";
    try {
      if (mode === "full") {
        const ready = await env.DB.prepare(`
          UPDATE poc_sources SET due_at=?
          WHERE id=? AND lease_token IS NULL
        `).bind("1970-01-01T00:00:00.000Z", SOURCE_ID).run();
        if (ready.meta.changes !== 1) throw new Error("source_not_released");
        const outcome = await collectDue(env, event.scheduledTime);
        if (outcome.processed !== 1 || outcome.errors !== 0 || outcome.leaseConflicts !== 0)
          throw new Error("full_ingest_incomplete");
        inserted = outcome.inserted;
      } else {
        const text = await fetchLimited(SOURCE_URL, (req) => env.TEST_FEED_FETCHER ? env.TEST_FEED_FETCHER.fetch(req) : fetch(req));
        if (mode === "parse") {
          articles = parseWithFastXml(text, SOURCE_URL).length;
          if (!articles) throw new Error("empty_feed");
        } else {
          articles = text.length;
        }
      }
      success = true;
    } catch (err) {
      errorCode = err instanceof Error && ["source_not_released", "full_ingest_incomplete", "empty_feed"].includes(err.message) ? err.message : "upstream_or_runtime_failure";
    }
    const durationMs = Date.now() - start;
    await env.DB.prepare(`
      INSERT INTO gln003_profile_samples(run,mode,success,articles,inserted,wall_ms,error_code)
      VALUES (?,?,?,?,?,?,?)
    `).bind(plan.run, mode, success ? 1 : 0, articles, inserted, durationMs, errorCode).run();
    console.log(JSON.stringify({
      event: "gln003_cpu_profile",
      run: plan.run,
      mode,
      success,
      articles,
      inserted,
      durationMs,
      errorCode
    }));
  }
};
export {
  gln003_profile_worker_default as default
};
